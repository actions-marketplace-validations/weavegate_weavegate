#!/usr/bin/env python3
"""Regenerate the reviewed fixture contract from its immutable Git tree.

This is a maintainer build, not a measurement or a manifest-supplied authority.
Review changes to its output before admitting newly compiled fixture classes.
"""
import argparse
import os
from pathlib import Path
import pprint
import subprocess
import tempfile
import runpy

runpy.run_path(str(Path(__file__).resolve().with_name('imports.py')),
              init_globals={'dependencies': ('support',)})
from support import WORKLOADS, digest, files, inventory, read_json, normalized_fixture_config

REVISION = 'e1bd8ba3fc07d024b8cb4037aa2263d24044dbb0'


def record(root, baseline, classpaths, javac, output):
    root, baseline, classpaths, javac = [Path(p).resolve() for p in (root, baseline, classpaths, javac)]
    fixtures, libraries = {}, {}
    with tempfile.TemporaryDirectory() as temporary:
        checkout = Path(temporary)
        for workload, (fixture, scenario, *_) in WORKLOADS.items():
            prefix = 'fixtures/' + fixture
            names = subprocess.check_output(
                ['git', 'ls-tree', '-r', '--name-only', REVISION, prefix], cwd=root, text=True).splitlines()
            for name in names:
                target = checkout/name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(subprocess.check_output(['git', 'show', REVISION+':'+name], cwd=root))
            base = checkout/prefix
            exported = checkout/(workload+'-inputs')
            subprocess.run([str(baseline), '--arm', 'inputs', '--config', str(base/'.weavegate/config.yaml'),
                            '--scenario', scenario, '--variant', 'vulnerable', '--out', str(exported)], check=True)
            libs = sorted((classpaths/(workload+'-classpath/BOOT-INF/lib')).glob('*.jar'))
            if not libs:
                raise ValueError('missing reference build libraries: '+workload)
            libraries[workload] = {p.name: digest(p) for p in libs}
            classes = checkout/(workload+'-classes'); classes.mkdir()
            subprocess.run([str(javac), '-g', '-parameters', '--release', '21',
                            '-cp', os.pathsep.join(map(str, libs)), '-d', str(classes),
                            *map(str, sorted((base/'app/src/main/java').rglob('*.java')))], check=True)
            fixtures[workload] = {
                'config': normalized_fixture_config(read_json(exported/'inputs.json')['config']),
                'migrations': inventory(base/'db/migration'),
                'seed_sha256': digest(base/'db/seed.sql'),
                'business_classes': inventory(classes),
                'source_files': {str(p.relative_to(base)): digest(p) for p in files(base)},
            }
    build = {'javac': subprocess.check_output([str(javac), '-version'], text=True).strip(),
             'javac_sha256': digest(javac), 'exporter_sha256': digest(baseline),
             'compiler_flags': ['-g', '-parameters', '--release', '21'], 'libraries': libraries}
    output = Path(output)
    output.write_text('"""Generated by record_fixture_contract.py; review before replacing the authority."""\n'
                      + 'FIXTURE_REVISION = '+repr(REVISION)+'\n\n'
                      + 'FIXTURE_INPUTS = '+pprint.pformat(fixtures, sort_dicts=True, width=110)+'\n\n'
                      + 'REFERENCE_BUILD = '+pprint.pformat(build, sort_dicts=True, width=110)+'\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', default=str(Path(__file__).resolve().parents[3]))
    parser.add_argument('--baseline', required=True)
    parser.add_argument('--classpaths', required=True)
    parser.add_argument('--javac', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    record(args.root, args.baseline, args.classpaths, args.javac, args.output)
